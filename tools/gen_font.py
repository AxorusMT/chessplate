def emit_bytes(name, data):
    out = [f"static const unsigned char {name}[{max(len(data), 1)}] = {{"]
    row = []
    for i, b in enumerate(data):
        row.append(str(b))
        if len(row) == 40:
            out.append(",".join(row) + ",")
            row = []
    if row:
        out.append(",".join(row) + ",")
    if not data:
        out.append("0")
    out.append("};")
    return "\n".join(out)


def main():
    print(HEADER)
    font_entries = []
    for ident, filename, size in FONTS:
        font = ImageFont.truetype(os.path.join(FONT_DIR, filename), size)
        ascent, descent = font.getmetrics()
        bitmap = bytearray()
        glyphs = []
        for code in range(FIRST, LAST + 1):
            ch = chr(code)
            advance = font.getlength(ch)
            x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
            w, h = max(x1 - x0, 0), max(y1 - y0, 0)
            offset = len(bitmap)
            if w > 0 and h > 0:
                img = Image.new("L", (w, h), 0)
                ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
                bitmap.extend(img.tobytes())
            glyphs.append((x0, y0, w, h, advance, offset))

        print(emit_bytes(f"{ident}_bitmap", bitmap))
        print(f"static const GlyphInfo {ident}_glyphs[{LAST - FIRST + 1}] = {{")
        for x0, y0, w, h, adv, off in glyphs:
            print(f"  {{{x0}, {y0}, {w}, {h}, {adv:.3f}f, {off}}},")
        print("};")
        font_entries.append((ident, ascent, descent))

    print("\nconst FontData font_table[FONT_COUNT] = {")
    for ident, ascent, descent in font_entries:
        print(f"  {{{ascent}, {descent}, {ident}_glyphs, {ident}_bitmap}},")
    print("};")


if __name__ == "__main__":
    main()
