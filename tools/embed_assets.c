/*
 * Generates src/assets.c, embedding the SVG assets as C strings.
 *
 *   cc -o build/embed_assets tools/embed_assets.c
 *   build/embed_assets assets > src/assets.c
 *
 * (`make assets` does this.)
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static const struct {
    const char *symbol;
    const char *path;
} ENTRIES[] = {
    {"asset_logo_svg", "logo/chessplate-logo.svg"},
    {"asset_wK_svg", "pieces/wK.svg"},
    {"asset_wQ_svg", "pieces/wQ.svg"},
    {"asset_wR_svg", "pieces/wR.svg"},
    {"asset_wB_svg", "pieces/wB.svg"},
    {"asset_wN_svg", "pieces/wN.svg"},
    {"asset_wP_svg", "pieces/wP.svg"},
    {"asset_bK_svg", "pieces/bK.svg"},
    {"asset_bQ_svg", "pieces/bQ.svg"},
    {"asset_bR_svg", "pieces/bR.svg"},
    {"asset_bB_svg", "pieces/bB.svg"},
    {"asset_bN_svg", "pieces/bN.svg"},
    {"asset_bP_svg", "pieces/bP.svg"},
};

int main(int argc, char **argv) {
    const char *root = argc > 1 ? argv[1] : "assets";
    printf("/* Generated by tools/embed_assets.c from the assets/ directory -- do not edit. */\n\n");
    printf("#include \"assets.h\"\n\n");

    for (size_t i = 0; i < sizeof(ENTRIES) / sizeof(ENTRIES[0]); i++) {
        char path[1024];
        snprintf(path, sizeof(path), "%s/%s", root, ENTRIES[i].path);
        FILE *f = fopen(path, "rb");
        if (!f) {
            fprintf(stderr, "embed_assets: cannot open %s\n", path);
            return 1;
        }
        printf("/* %s */\nconst char %s[] =\n    \"", ENTRIES[i].path, ENTRIES[i].symbol);
        int col = 0, c;
        while ((c = fgetc(f)) != EOF) {
            if (c == '\r') continue;
            if (c == '\n') {
                printf("\\n\"\n    \"");
                col = 0;
                continue;
            }
            if (c == '"' || c == '\\') printf("\\%c", c);
            else if (c < 32 || c > 126) printf("\\%03o", c);
            else putchar(c);
            if (++col >= 100) {
                printf("\"\n    \"");
                col = 0;
            }
        }
        fclose(f);
        printf("\";\nconst unsigned long %s_len = sizeof(%s) - 1;\n\n", ENTRIES[i].symbol, ENTRIES[i].symbol);
    }
    return 0;
}
